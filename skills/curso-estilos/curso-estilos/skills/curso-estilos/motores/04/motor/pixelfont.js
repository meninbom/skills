// accents: [base, mark] ; marks drawn in the 2 rows above the glyph (or below for cedilla)
const ACC = { 'Á': ['A', 'acute'], 'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ã': ['A', 'tilde'], 'É': ['E', 'acute'], 'Ê': ['E', 'circ'], 'Í': ['I', 'acute'],
  'Ó': ['O', 'acute'], 'Ô': ['O', 'circ'], 'Õ': ['O', 'tilde'], 'Ú': ['U', 'acute'], 'Ç': ['C', 'ced'] };
const MARK = { acute: ['...#.', '..#..'], grave: ['.#...', '..#..'], circ: ['..#..', '.#.#.'], tilde: ['.#.##', '##.#.'], ced: ['..#..', '.##..'] };

export function textWidth(str, px, spacing = 1) { return [...str].length * (5 + spacing) * px - spacing * px; }

// draw str with its top-left at (x, y); px = size of one font pixel. opts: color, shadow, alpha
export function drawText(ctx, str, x, y, px, color = '#ffe2aa', opts = {}) {
  const sp = opts.spacing ?? 1, sh = opts.shadow ?? 'rgba(20,12,30,0.85)';
  const chars = [...str.toUpperCase()];
  const blit = (rows, ox, oy, c) => { ctx.fillStyle = c; rows.forEach((r, j) => { for (let i = 0; i < 5; i++) if (r[i] === '#') ctx.fillRect(ox + i * px, oy + j * px, px, px); }); };
  const draw = (dx, dy, c) => {
    let cx = x + dx;
    for (const ch of chars) {
      let base = ch, mark = null;
      if (ACC[ch]) [base, mark] = ACC[ch];
      const g = G[base] || G['?'];
      blit(g, cx, y + dy, c);
      if (mark === 'ced') blit(MARK.ced, cx, y + dy + 7 * px, c);
      else if (mark) blit(MARK[mark], cx, y + dy - 2.5 * px, c);
      cx += (5 + sp) * px;
    }
  };
  if (sh) { draw(px * 0.75, px * 0.75, sh); draw(-px * 0.25, px * 0.75, sh); }
  draw(0, 0, color);
}
export { G, ACC, MARK };
