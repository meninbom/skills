CORES = {'rosa': (0xFF, 0x4F, 0xA3), 'azul': (0x31, 0x57, 0xFF), 'lima': (0x9A, 0xDB, 0x2A), 'tinta': (0x1B, 0x16, 0x31)}
# uma lima só (#9ADB2A) em tudo
COR_DE = {'sol': 'lima', 'nuvem': 'azul', 'coracao': 'rosa', 'lampada': 'lima', 'bomba': 'tinta',
          'lua': 'azul', 'guarda': 'rosa', 'nota': 'tinta', 'estrela': 'lima', 'gota': 'azul'}


def grade(n):
    linhas = [l for l in ICON[n].strip('\n').split('\n')]
    assert len(linhas) == 12 and all(len(l) == 12 for l in linhas), n
    return np.array([[c == '#' for c in l] for l in linhas])


if __name__ == '__main__':
    os.makedirs('px', exist_ok=True)
    CEL = 40  # px por pixel no PNG (×1,5 do tamanho em tela de ~26 px)
    for n in ICON:
        g = grade(n)
        m = np.kron(g, np.ones((CEL, CEL), bool))
        rgb = np.zeros(m.shape + (3,), np.uint8); rgb[m] = CORES[COR_DE[n]]
        adesivo(rgb, m, borda=22, nome=f'../px/{n}')
    json.dump({n: [''.join('#' if c else '.' for c in row) for row in grade(n)] for n in ICON} | {'_cor': {n: '#%02X%02X%02X' % CORES[COR_DE[n]] for n in ICON}},
              open('px/icones.json', 'w'), indent=1)
