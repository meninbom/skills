// acentos (2 linhas) para minúsculas: ficam nas linhas 0-1, acima do x-height
const AC = {
  "´": ["...#.", "..#.."],
  "`": [".#...", "..#.."],
  "^": ["..#..", ".#.#."],
  "~": [".##.#", "#.##."],
};
function sobrepor(base, ac, off = 0) {
  const rows = base.map((r) => r.split(""));
  for (let j = 0; j < 2; j++) for (let i = 0; i < ac[j].length; i++) {
    const x = i + off;
    if (ac[j][i] === "#" && x >= 0 && x < rows[j].length) rows[j][x] = "#";
  }
  return rows.map((r) => r.join(""));
}
